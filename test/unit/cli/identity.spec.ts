import { describe, expect, it } from 'vitest';

import { removeIdentity } from '../../../src/cli/identity.js';
import { deleteIdentity } from '../../../src/cli/install.js';
import { connectionName } from '../../../src/cli/installation.js';
import { fakeCloud } from './fakes.js';

const connection = (cloud: 'aws' | 'gcp' | 'azure') =>
  connectionName(cloud, 'backmesh-1-abcd');

describe('removeIdentity', () => {
  it.each([
    [
      'aws' as const,
      [
        'aws iam list-user-tags --user-name anycloud-bm-aws-x --output json',
        'aws iam list-access-keys --user-name anycloud-bm-aws-x --output json',
        'aws iam delete-access-key --user-name anycloud-bm-aws-x --access-key-id AK1',
        'aws iam list-user-policies --user-name anycloud-bm-aws-x --output json',
        'aws iam delete-user-policy --user-name anycloud-bm-aws-x --policy-name AnycloudAccess',
        'aws iam list-attached-user-policies --user-name anycloud-bm-aws-x --output json',
        'aws iam delete-user --user-name anycloud-bm-aws-x',
      ],
    ],
    [
      'gcp' as const,
      [
        'gcloud config get-value project',
        'gcloud iam service-accounts describe anycloud-bm-gcp-x@p1.iam.gserviceaccount.com --project p1 --format json',
        ...[
          'roles/compute.instanceAdmin.v1',
          'roles/compute.securityAdmin',
          'roles/storage.admin',
          // The grant upgrade names for a key connection.
          'projects/p1/roles/anycloudJobsNetwork',
        ].map(
          (role) =>
            `gcloud projects remove-iam-policy-binding p1 --member serviceAccount:anycloud-bm-gcp-x@p1.iam.gserviceaccount.com --role ${role} --condition None --format none`,
        ),
        'gcloud iam service-accounts delete anycloud-bm-gcp-x@p1.iam.gserviceaccount.com --project p1 --quiet',
      ],
    ],
    [
      'azure' as const,
      [
        'az ad app list --display-name anycloud-bm-azure-x --output json',
        'az account show --query id --output tsv',
        'az role assignment delete --assignee app-anycloud-bm-azure-x --scope /subscriptions/sub-1',
        'az ad app delete --id app-anycloud-bm-azure-x',
      ],
    ],
  ])(
    "deletes %s's generated identity and its grants, then finds it gone",
    async (cloud, commands) => {
      const name = `bm-${cloud}-x`;
      const fake = fakeCloud([`anycloud-${name}`]);
      expect(await removeIdentity(cloud, name, fake.command)).toMatch(
        new RegExp(`^Deleted ${cloud}'s identity anycloud-${name}, which`),
      );
      expect(fake.calls).toEqual(commands);
      expect(fake.live.size).toBe(0);
      // A re-run changes nothing and says where it looked.
      fake.calls.length = 0;
      const again = await removeIdentity(cloud, name, fake.command);
      expect(again).toBe(
        `${cloud}'s identity anycloud-${name} isn't in the ${{ aws: 'account', gcp: 'project', azure: 'subscription' }[cloud]} ${cloud}'s CLI is signed in to. If install generated it in another, delete it there with:\n${deleteIdentity(cloud, name)}`,
      );
      expect(fake.calls.some((c) => / delete/.test(c))).toBe(false);
    },
  );

  it.each(['aws', 'gcp', 'azure'] as const)(
    "leaves %s's identity of that name without anycloud's marks",
    async (cloud) => {
      const name = connection(cloud);
      const fake = fakeCloud([`anycloud-${name}`], { unmarked: true });
      expect(await removeIdentity(cloud, name, fake.command)).toMatch(
        /wasn't generated by anycloud, so uninstall left it\.$/,
      );
      expect(fake.calls.some((c) => / delete/.test(c))).toBe(false);
      expect(fake.live.size).toBe(1);
    },
  );

  it.each([
    ['aws' as const, 'delete-user '],
    ['gcp' as const, 'remove-iam-policy-binding'],
    ['azure' as const, 'role assignment delete'],
  ])(
    "prints %s's commands when its CLI is refused, without failing",
    async (cloud, refuse) => {
      const name = connection(cloud);
      const fake = fakeCloud([`anycloud-${name}`], { refuse });
      expect(await removeIdentity(cloud, name, fake.command)).toBe(
        `${cloud}'s identity anycloud-${name} wasn't deleted (AccessDenied: not allowed). Delete it, signed in to the ${{ aws: 'account', gcp: 'project', azure: 'subscription' }[cloud]} install used, with:\n${deleteIdentity(cloud, name)}`,
      );
    },
  );
});

describe('connectionName', () => {
  it('is short, stable and valid as every cloud names its generated identity', () => {
    for (const id of ['c1', 'backmesh-1-abcd', 'backmesh-20261117-zzzz']) {
      for (const cloud of ['aws', 'gcp', 'azure'] as const) {
        const name = connectionName(cloud, id);
        expect(name).toBe(connectionName(cloud, id));
        expect(name).toMatch(new RegExp(`^bm-${cloud}-[a-z0-9]{6}$`));
        // GCP's service account ID: 6–30 of [a-z0-9-], a letter first.
        expect(`anycloud-${name}`).toMatch(/^[a-z][a-z0-9-]{4,28}[a-z0-9]$/);
      }
    }
    expect(connectionName('aws', 'c1')).not.toBe(connectionName('aws', 'c2'));
  });
});
