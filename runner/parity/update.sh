#!/usr/bin/env bash
# Writes toolset.lock: the apt packages GitHub's Ubuntu 24.04 image installs
# (actions/runner-images toolset-2404.json: vital, common and cmd), at one
# runner-images commit, by default main's. The image installs them, and
# gaps.sh checks the image against that commit's README.
set -Eeuo pipefail

dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
rev=${1:-$(curl -fsSL https://api.github.com/repos/actions/runner-images/commits/main | jq -r .sha)}
[[ $rev =~ ^[0-9a-f]{40}$ ]] || { echo "Not a commit SHA: $rev" >&2; exit 1; }
toolset=$(curl -fsSL "https://raw.githubusercontent.com/actions/runner-images/$rev/images/ubuntu/toolsets/toolset-2404.json")
{
  echo '# Generated by runner/parity/update.sh; the nightly runner-toolset workflow bumps it.'
  echo "revision=$rev"
  # With commands.txt's apt: replacements, for packages Ubuntu installs only
  # by another name.
  jq -r '.apt | .vital_packages + .common_packages + .cmd_packages | .[]' <<<"$toolset" \
    | awk 'FNR == NR { if (sub(/^apt:/, "")) { split($0, kv, "="); to[kv[1]] = kv[2] } next }
      { print $0 in to ? to[$0] : $0 }' "$dir/commands.txt" - | sort -u
} >"$dir/toolset.lock.new"
mv "$dir/toolset.lock.new" "$dir/toolset.lock"
